    # --------------------------------------------------------------------------
    # 5. Real Emulator: Citizen Data Isolation & Cross-Tenant Protection
    # --------------------------------------------------------------------------
    def test_05_real_emulator_citizen_data_isolation(self):
        """Predictions submitted by Citizen A are strictly isolated from Citizen B."""
        # 1. Citizen A creates a prediction
        files = {"file": ("citizena_waste.jpg", self.valid_image_bytes, "image/jpeg")}
        resp_pred = self.client.post(
            "/api/predict",
            files=files,
            headers={"Authorization": f"Bearer {self.citizen_a_token}"}
        )
        self.assertEqual(resp_pred.status_code, 200)

        # Locate Citizen A's latest record
        records_a = storage_service.list_records(limit=1, user_id=self.citizen_a_uid)
        self.assertGreater(len(records_a), 0)
        citizen_a_record_id = records_a[0]["id"]

        # 2. Citizen B queries history: must not see Citizen A's record
        resp_hist_b = self.client.get(
            "/api/history",
            headers={"Authorization": f"Bearer {self.citizen_b_token}"}
        )
        self.assertEqual(resp_hist_b.status_code, 200)
        records_b = resp_hist_b.json()
        record_ids_b = [r["id"] for r in records_b]
        self.assertNotIn(citizen_a_record_id, record_ids_b)

        # 3. Citizen B attempts direct lookup: receives HTTP 403
        resp_inspect_b = self.client.get(
            f"/api/history/{citizen_a_record_id}",
            headers={"Authorization": f"Bearer {self.citizen_b_token}"}
        )
        self.assertEqual(resp_inspect_b.status_code, 403)

        # 4. Anonymous user attempts lookup: receives HTTP 401
        resp_anon = self.client.get(f"/api/history/{citizen_a_record_id}")
        self.assertEqual(resp_anon.status_code, 401)

    # --------------------------------------------------------------------------
    # 6. Real Emulator: Malformed, Tampered & Wrong-Audience Tokens (HTTP 401)
    # --------------------------------------------------------------------------
    def test_06_real_emulator_malformed_and_tampered_tokens(self):
        """Malformed or tampered emulator tokens fail cryptographic verification with HTTP 401."""
        # Malformed header
        resp_bad = self.client.get("/api/auth/me", headers={"Authorization": "Bearer not_a_jwt"})
        self.assertEqual(resp_bad.status_code, 401)

        # Tampered token: modify middle payload of genuine token
        parts = self.citizen_a_token.split(".")
        if len(parts) >= 2:
            tampered_token = f"{parts[0]}.eyJ1aWQiOiJhdHRhY2tlciJ9.{parts[2] if len(parts) > 2 else ''}"
            resp_tampered = self.client.get("/api/auth/me", headers={"Authorization": f"Bearer {tampered_token}"})
            self.assertEqual(resp_tampered.status_code, 401)

