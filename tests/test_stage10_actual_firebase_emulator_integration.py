class TestStage10ActualFirebaseEmulatorIntegration(unittest.TestCase):
    """
    Genuine live integration test suite interacting with the actual Firebase
    Authentication Emulator running locally on port 9099.
    """

    @classmethod
    def setUpClass(cls):
        cls._orig_env = dict(os.environ)

        # 1. Verify live emulator is accessible on port 9099
        try:
            req = urllib.request.Request(f"http://{EMULATOR_HOST}/")
            with urllib.request.urlopen(req, timeout=3) as resp:
                pass
        except Exception as e:
            raise unittest.SkipTest(f"Live Firebase Auth Emulator is not accessible on {EMULATOR_HOST}: {e}")

        # 2. Configure environment for live emulator testing
        os.environ["ENVIRONMENT"] = "development"
        os.environ["AUTH_PROVIDER"] = "firebase"
        os.environ["ALLOW_DEV_AUTH"] = "false"
        os.environ["GOOGLE_CLOUD_PROJECT"] = PROJECT_ID
        os.environ["FIREBASE_AUTH_EMULATOR_HOST"] = EMULATOR_HOST
        os.environ["ADMIN_EMAILS"] = "admin@sanitation.gov"
        os.environ["STORAGE_PROVIDER"] = "local"

        # 3. Initialize Firebase Admin against live emulator
        security_config.reload()
        token_verifier._init_firebase_admin()

        cls.client = TestClient(app)

        # Generate valid JPEG image bytes for real model inference tests
        img = Image.new("RGB", (224, 224), color=(80, 160, 220))
        buf = io.BytesIO()
        img.save(buf, format="JPEG")
        cls.valid_image_bytes = buf.getvalue()

        # Track created UIDs for cleanup
        cls.created_uids = []

        # 4. Create genuine test users in emulator
        # Citizen A
        user_a = emulator_sign_up(f"citizena_{int(time.time())}@local.eco")
        cls.citizen_a_uid = user_a["localId"]
        cls.citizen_a_token = user_a["idToken"]
        cls.created_uids.append(cls.citizen_a_uid)

        # Citizen B
        user_b = emulator_sign_up(f"citizenb_{int(time.time())}@local.eco")
        cls.citizen_b_uid = user_b["localId"]
        cls.citizen_b_token = user_b["idToken"]
        cls.created_uids.append(cls.citizen_b_uid)

        # Verified Admin (in ADMIN_EMAILS whitelist, marked email_verified=True)
        admin_data = emulator_sign_up(f"admin_{int(time.time())}@sanitation.gov")
        cls.admin_uid = admin_data["localId"]
        cls.created_uids.append(cls.admin_uid)
        # Update email to match exact whitelist and mark verified
        auth.update_user(cls.admin_uid, email="admin@sanitation.gov", email_verified=True)
        admin_login = emulator_sign_in("admin@sanitation.gov")
        cls.admin_token = admin_login["idToken"]

        # Unverified Admin Candidate (matching whitelist email domain, but email_verified=False)
        unverified_data = emulator_sign_up(f"unverified_{int(time.time())}@sanitation.gov")
        cls.unverified_uid = unverified_data["localId"]
        cls.created_uids.append(cls.unverified_uid)
        auth.update_user(cls.unverified_uid, email="admin-unverified@sanitation.gov", email_verified=False)
        unverified_login = emulator_sign_in("admin-unverified@sanitation.gov")
        cls.unverified_token = unverified_login["idToken"]

