def emulator_sign_up(email: str, password: str = "Password123!") -> dict:
    """Creates a user on the live Firebase Auth Emulator via REST API."""
    url = f"http://{EMULATOR_HOST}/identitytoolkit.googleapis.com/v1/accounts:signUp?key=fake-key"
    payload = json.dumps({
        "email": email,
        "password": password,
        "returnSecureToken": True
    }).encode("utf-8")
    req = urllib.request.Request(url, data=payload, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req) as resp:
        return json.loads(resp.read().decode("utf-8"))


